import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';

const html = readFileSync('index.html', 'utf8');
const inline = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
const dom = new JSDOM(html, { url: 'https://sprout.test/', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
w.requestAnimationFrame = () => 0;
w.HTMLCanvasElement.prototype.getContext = () => new Proxy({}, { get: () => () => {} });
w.eval(inline + '\nwindow.__state=()=>S;window.__party=()=>party;');
const s = w.__state(), c = s.chars[s.active];
s.profileStarted = true;
const st = w.calcStats();
const h200 = w.stageCombatHp(200, false, st), h500 = w.stageCombatHp(500, false, st);
if (!(h500 / h200 > 3)) throw Error('Late stage enemy health growth too flat');
if (!Number.isFinite(w.stageHealthTarget(5000))) throw Error('Very late stage health overflow');
if (c.stageHpBalanceVersion !== 36) throw Error('Existing cached health was not invalidated');
s.rebirthUpgrades.speed = 2;
const haste = { trait: { type: 'haste', lv: 3 } };
c.equipment['반지'] = haste;
const buff = w.calcStats();
if (buff.aspd !== st.aspd || buff.finalDmg <= st.finalDmg || buff.equipTraitBonus.finalPct !== .09) throw Error('Non-growth speed buff migration failed');
delete c.equipment['반지'];
c.worldBossCleared = 1280;
c.highest = 1300;
w.openParty(1300);
const before = s.transcendTickets, bonus = w.worldBossBonusTickets(1300), tickets = s.equipTickets;
w.__party().bossHp = 1;
w.__party().bossMaxHp = 100;
w.partyAction('assault');
if (s.transcendTickets !== before + 1 || s.equipTickets < tickets + bonus + 1000) throw Error('Guaranteed boss ticket and bonus did not both apply');
if (w.riftHTML().includes('현재 캐릭터 최고 스테이지 200부터 개방')) throw Error('Rift unexpectedly locked');
s.riftUpgrades.attack = 2;
if (!(w.calcStats().atk > st.atk * 1.07)) throw Error('Rift attack upgrade too weak');
if (!w.equipmentHTML().includes('장비 전서')) throw Error('Equipped slot overview missing');
const ancient = { id: 'ancient-smoke', ownerJob: s.active, name: '고대 장비', rarity: '고대', slot: '무기', power: 100, cls: 'rarity-ancient' };
s.equipmentInventory.push(ancient);
s.autoTrashThreshold = '초월';
w.bulkSalvage();
if (s.equipmentInventory.some(x => x.id === ancient.id)) throw Error('Ancient equipment was excluded from bulk salvage');
s.compTickets = 5000;
w.summonComp(500);
if (s.gacha.compPity !== 0 || s.compTickets < 0) throw Error('Large summon batch failed');
const menu = w.companionsHTML();
if (!menu.includes('동료')) throw Error('Companion menu failed after batch summon');
if (s.companionInventory.length) {
  const chosen = s.companionInventory.at(-1);
  c.companions = [chosen];
  if (!w.companionsHTML().includes('<div class="compGrid"><div class="compCard active"')) throw Error('Active companion was not sorted first');
}
console.log('Late health growth, buff conversion, guaranteed boss ticket, rift, equipment overview and 500 companion summons passed.');
w.close();
